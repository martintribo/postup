#!/usr/bin/env python3
"""Port the mockup CSS (postup-pm/mockups/gen/{style,themes,desktop}.css) into src/lib/styles/ui.css.
Drops phone-frame / mockup-chrome rules, maps [data-style=X] -> [data-theme=X], and turns
[data-device=desktop] into a min-width:1024px media query. Re-run after mockup changes."""
import re, sys, pathlib
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/workspace/postup-pm/mockups/gen')
DROP = re.compile(r'(^|[\s,>+~(])(\.dev|\.ph|\.sb|\.mock|\.scr|\.dvsw|\.stsw|body|html|\*|\.isl|\.sbi)(?![\w-])')
def rules(css):
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        sel = css[i:j].strip(); depth = 1; k = j + 1
        while depth and k < n:
            depth += {'{': 1, '}': -1}.get(css[k], 0); k += 1
        out.append((sel, css[j + 1:k - 1])); i = k
    return out
def keep(sel):
    if sel.startswith('@keyframes'): return True
    parts, depth, cur = [], 0, ''
    for ch in sel:
        depth += (ch == '(') - (ch == ')')
        if ch == ',' and depth == 0: parts.append(cur); cur = ''
        else: cur += ch
    parts.append(cur)
    parts = [p for p in parts if not DROP.search(' ' + p.strip())]
    return ','.join(parts)
DESK = []
def emit(css, desktop=False):
    res = []
    for sel, body in rules(re.sub(r'/\*.*?\*/', '', css, flags=re.S)):
        if sel.startswith('@media'):
            continue  # phone-frame media blocks
        if sel.startswith('@keyframes'):
            res.append(f'{sel}{{{body}}}'); continue
        if not desktop and '[data-device=desktop]' in sel:
            DESK.append((sel, body)); continue
        if desktop: sel = re.sub(r'\[data-device=desktop\]', '', sel)
        # Mockup screens (#project, .scr:is(#a,#b)) map to page roots with class scr-<id>.
        sel = re.sub(r'\.scr:is\(([^)]*)\)', lambda m: ':is(' + re.sub(r'#([a-z][\w-]*)', r'.scr-\1', m.group(1)) + ')', sel)
        sel = re.sub(r'(?<![\w-])#([a-z][\w-]*)', r'.scr-\1', sel)
        sel = re.sub(r'\[data-style=(\w+)\]', r"[data-theme='\1']", sel)
        sel = re.sub(r'\[data-theme=\'(\w+)\'\]\s*:root', r"[data-theme='\1']", sel)
        k = keep(sel)
        if k is True: k = sel
        if not k or not k.strip(): continue
        if sel.strip() == ':root' or re.fullmatch(r"\[data-theme='\w+'\]", sel.strip()):
            res.append(f'{sel}{{{body}}}'); continue
        res.append(f'{k.strip()}{{{body}}}')
    return '\n'.join(res)
style = (SRC / 'style.css').read_text(); themes = (SRC / 'themes.css').read_text(); desk = (SRC / 'desktop.css').read_text()
out = ['/* GENERATED by scripts/port-mockup-css.py from the mockups. Do not edit; override in app.css. */',
       '@layer components {', emit(style), emit(themes), '@media (min-width: 1024px) {', emit(desk, True), '}', '}']
out.insert(-2, emit('\n'.join(f'{a}{{{b}}}' for a, b in DESK), True))
pathlib.Path('src/lib/styles/ui.css').write_text('\n'.join(out) + '\n')
print('wrote src/lib/styles/ui.css', sum(len(x) for x in out))
